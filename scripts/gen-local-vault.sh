#!/usr/bin/env bash
# Creates the secrets of the local server once (docs/adr/0006-local-secrets-and-tls.md):
#
#   local/.vault-pass                                    random vault password
#   ansible/inventories/local/group_vars/all/vault.yml   encrypted, random values
#
# Both are gitignored: the local environment is disposable, and a secret
# that never leaves the workstation cannot leak through the repository.
# Existing files are never overwritten (the database was initialised with
# the password in them). Runs in the toolbox; prints no secret.
set -euo pipefail

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
pass_file="$repo_root/local/.vault-pass"
vault_file="$repo_root/ansible/inventories/local/group_vars/all/vault.yml"

# rand LENGTH: URL-safe random characters (no quoting needed in YAML,
# env files or a connection string).
rand() { python3 -c "import secrets, sys; print(secrets.token_urlsafe(64)[:int(sys.argv[1])])" "$1"; }

if [[ ! -f "$pass_file" ]]; then
  rand 48 >"$pass_file"
  echo "Created local/.vault-pass" >&2
fi

if [[ ! -f "$vault_file" ]]; then
  tmp="$(mktemp)"
  trap 'rm -f "$tmp"' EXIT
  cat >"$tmp" <<EOF
# Secrets of the local server, generated by scripts/gen-local-vault.sh.
# View: make shell, then
#   ansible-vault view ansible/inventories/local/group_vars/all/vault.yml
postgres_password: $(rand 32)
jwt_secret: $(rand 48)
telegram_bot_token: ""
grafana_admin_password: $(rand 24)
alertmanager_telegram_chat_id: ""
healthchecks_ping_url: ""
s3_access_key: ""
s3_secret_key: ""
EOF
  ansible-vault encrypt --vault-password-file "$pass_file" --output "$vault_file" "$tmp" >/dev/null
  echo "Created the encrypted local vault (ansible/inventories/local/group_vars/all/vault.yml)" >&2
fi
